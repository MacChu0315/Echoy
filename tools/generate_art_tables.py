"""Freeze time-independent artwork math; regenerate the C header with Python 3."""
from pathlib import Path
import math
root = Path(__file__).resolve().parents[1]
def values(name, values):
    return 'static const double '+name+'[] = {\n'+''.join('    '+v.hex()+',\n' for v in values)+'};\n'
s='/* Generated by tools/generate_art_tables.py. Do not edit by hand. */\n#pragma once\n'
s+=values('voice_window',[math.pow(math.sin(i/140.0*math.pi),1.6) for i in range(141)])
s+=values('harmony_arch',[math.sin(math.pi*(i/135.0)) for i in range(136)])
for row in range(3):s+=values('harmony_wave_'+str(row),[math.sin(i/135.0*math.pi*2+row*.3)*5 for i in range(136)])
def rand(n):
    v=math.sin(n*127.1+311.7)*43758.5453
    return v-math.floor(v)
s+=values('dust_u',[rand(i+1) for i in range(135)])
s+=values('dust_v',[rand(i+54) for i in range(135)])
s+=values('dust_radius',[rand(i+8)*.6 for i in range(135)])
s+=values('dust_y',[89+math.sin(rand(i+1)*7)*13+(rand(i+54)-.5)*(35*math.sin(rand(i+1)*math.pi)+10)*2 for i in range(135)])
(root/'projects/echoy/main/echoy_art_tables.h').write_text(s)
