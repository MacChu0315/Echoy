#!/usr/bin/env python3
"""Frozen UI input adapter; no pixels, expected labels or layout in renderer fixtures."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
cases=json.loads((root/'tests/cases/ui-cases.json').read_text())['cases'];caps=json.loads((root/'tests/cases/ui-capture.json').read_text())['cases']
roles=['pulse','voice','dust','harmony'];kinds=['kick','rim','hat','tone','grain','chord']
lines=['// Generated by tools/generate_ui_cases.py from frozen Task 1 inputs.','typedef struct {const char *id,*branch,*state; int role,phrase,route,battery; double activity,committed,volume; echoy_motif_t motif;} ui_fixture_t;','static const ui_fixture_t fixtures[]={']
for c,cap in zip(cases,caps):
 es=[]
 for e in cap['motif']:
  fields=[f'.{k}={json.dumps(e[k])}' for k in ['step','vel','note','dur','expression','accent'] if k in e]
  fields.append('.kind=%d'%kinds.index(e['kind']))
  for k in ['notes','harmony']:
   if k in e:fields.extend([f'.{k}={{'+','.join(map(str,e[k]))+'}',f'.{k}_count={len(e[k])}',f'.has_{k}=true'])
  es.append('{'+','.join(fields)+'}')
 vals=[json.dumps(c['locale']+'/'+c['id']),json.dumps(c.get('feedbackBranch','')),json.dumps(c['state']),str(roles.index(c['role'])),str(c['phrase']),str(1 if c['route']=='role' else 0),str(c.get('battery',86)),str(c['activity']),str(c.get('committedActivity',c['activity'])),str(c.get('volume',.7))]
 lines.append('{'+','.join(vals)+', {.count=%d,.events={'%len(es)+','.join(es)+'}}},')
lines+=['};'];(root/'pc/ui_fixtures.inc').write_text('\n'.join(lines)+'\n')
