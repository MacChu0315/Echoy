#!/usr/bin/env python3
"""Generate pinned, subset-source LVGL fonts; never edit generated C.
Requires Pillow 10.4.0 and fontTools 4.53.1; source provenance in manifest.json.
"""
from pathlib import Path
import hashlib,json,sys
from fontTools.ttLib import TTFont
from fontTools import subset
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]; OUT=ROOT/'assets/fonts'
CAP=json.loads((ROOT/'tests/cases/ui-capture.json').read_text())
corpus=''.join(c['screen']['text'] for c in CAP['cases'])+'D / MINOR RESPONSE PHRASE STACCATO ARPEGGIO ANSWER PARTICLES / LOCAL AIR RUN READY PERC. HITS 01—16打击就绪演奏中重音D 小调回应乐句短和弦分解接句颗粒 / 本机空气感ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 !?.,:%×←◉≋≡⠿▶Ⅱ• ·，。等待恢复当前已保留待生效'
chars=''.join(sorted(set(corpus)-{'\n','\r','\t'},key=ord))
SOURCES=[('latin-regular','/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf',0),('latin-bold','/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf',0),('cjk-regular','/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc',2),('cjk-bold','/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc',2),('mono-regular','/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',0),('mono-bold','/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf',0)]
SOURCES += [('symbols-regular','/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',0),('symbols-bold','/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',0)]
if '--pin' in sys.argv:
 manifest={'corpus':chars,'sourceFonts':[],'pillow':'10.4.0','fontTools':'4.53.1'}
 for name,path,index in SOURCES:
  font=TTFont(path,fontNumber=index); options=subset.Options(); options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*'];options.recalc_timestamp=False
  sub=subset.Subsetter(options=options);sub.populate(text=chars);sub.subset(font);p=OUT/(name+'.otf');font.save(p)
  manifest['sourceFonts'].append({'file':p.name,'original':path,'faceIndex':index,'originalSha256':hashlib.sha256(Path(path).read_bytes()).hexdigest(),'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
 for package in ['fonts-liberation2','fonts-noto-cjk','fonts-dejavu-core']:(OUT/(package+'-LICENSE.txt')).write_text('\n'.join(line.rstrip() for line in Path('/usr/share/doc/'+package+'/copyright').read_text().splitlines())+'\n')
 (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
for source in ['i18n.c','view.c']:
 missing_source={c for c in (ROOT/'components/echoy_ui'/source).read_text() if ord(c)>127 and c not in chars}
 assert not missing_source,(source,missing_source)
manifest=json.loads((OUT/'manifest.json').read_text());assert chars==manifest['corpus'],'Product corpus changed: rerun --pin and review added glyphs'
for f in manifest['sourceFonts']:assert hashlib.sha256((OUT/f['file']).read_bytes()).hexdigest()==f['sha256']
lines=['// Generated by tools/generate_ui_fonts.py. Font licenses/provenance in assets/fonts.','#include "lvgl.h"']
names=[]
for mono,bold in [(False,False),(False,True),(True,False)]:
 suffix='bold' if bold else 'regular'
 paths=[OUT/(f+'-'+suffix+'.otf') for f in (['mono','cjk','latin','symbols'] if mono else ['latin','cjk','mono','symbols'])]
 maps=[TTFont(p).getBestCmap() for p in paths]
 missing=[c for c in chars if not any(ord(c) in m for m in maps)]
 assert not missing,(suffix,missing)
 for size in ([9,10,12,13,17,22] if mono else [9,10,12,13,14,15,16,17,18,19,20,22,24,25,26,27,28,30,32,40,42,46,50,55]):
  code=size+100 if mono else size
  name=f'echoy_font_{code}_{int(bold)}'; names.append((code,int(bold),name))
  fonts=[ImageFont.truetype(str(p),size) for p in paths]
  selected=chars if size<=30 else ''.join(c for c in chars if ord(c)<128 or c in '脉冲声线微尘和声◉≋≡⠿▶Ⅱ×')
  bits=bytearray(); desc=['{0}']; cps=[]
  for ch in selected:
   ix=next(i for i,m in enumerate(maps) if ord(ch) in m);font=fonts[ix];box=font.getbbox(ch,anchor='ls');l,t,r,b=box;w,h=r-l,b-t
   im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-l,-t),ch,font=font,fill=255,anchor='ls')
   pixels=[round(v/17) for v in im.getdata()] if w*h else []
   if len(pixels)%2:pixels.append(0)
   desc.append('{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}'%(len(bits),round(font.getlength(ch)*16),w,h,l,-b))
   bits.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2));cps.append(ord(ch)-32)
  lines+=['static const uint8_t '+name+'_bitmap[]={'+','.join(map(str,bits))+'};','static const lv_font_fmt_txt_glyph_dsc_t '+name+'_glyph[]={'+','.join(desc)+'};', 'static const uint16_t '+name+'_unicode[]={'+','.join(map(str,cps))+'};', 'static const lv_font_fmt_txt_cmap_t '+name+'_cmap[]={ {.range_start=32,.range_length=%d,.glyph_id_start=1,.unicode_list=%s_unicode,.list_length=%d,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY} };'%(max(cps)+1,name,len(cps)), 'static const lv_font_fmt_txt_dsc_t '+name+'_dsc={.glyph_bitmap='+name+'_bitmap,.glyph_dsc='+name+'_glyph,.cmaps='+name+'_cmap,.cmap_num=1,.bpp=4};', 'static const lv_font_t '+name+'={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=%d,.base_line=%d,.dsc=&%s_dsc};'%(size+8,round(size*.22)+4,name)]
lines+=['const lv_font_t *echoy_font(int size,bool bold) {','switch(size){']
for size in sorted({n[0] for n in names}):lines.append(f'case {size}:return '+(f'&echoy_font_{size}_0;' if size>100 else f'bold?&echoy_font_{size}_1:&echoy_font_{size}_0;'))
lines+=['default:return &echoy_font_16_0;}}']
data='\n'.join(lines)+'\n';dest=ROOT/'components/echoy_ui/fonts.c'
if '--check' in sys.argv:assert dest.read_text()==data,'Generated fonts are stale'
else:dest.write_text(data)
print(f'Fonts: {len(chars)} glyphs, regular/bold verified, 24 sizes, {len(data)} generated bytes')
