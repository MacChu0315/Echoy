/* Build-host only: call the private production table builder directly. */
#include "echoy_audio.c"
#include "echoy_fixed_audio_format.h"
#include <stdio.h>

int main(int argc,char **argv)
{
    if(argc!=3)return 2;
    FILE *header=fopen(argv[1],"w"),*binary=fopen(argv[2],"wb");
    if(!header || !binary) { if(header)fclose(header); if(binary)fclose(binary); return 1; }
    workspace_t *work=malloc(sizeof(*work));
    if(!work) { fclose(header); fclose(binary); return 1; }
    workspace_init(work);
    /* Covers the generated Harmony chord range (48..82), with a small upper
     * margin. The public API's remaining MIDI pitches retain the exact builder.
     * Lookup uses harmonic count, so equivalent pitches share one table. */
    unsigned counts[37],count=0;
    for(int note=84;note>=48;note--) {
        unsigned harmonics=(unsigned)((SR/2-1)/midi(note));
        if(!count || counts[count-1]!=harmonics)counts[count++]=harmonics;
    }
    fprintf(header,"/* Generated by the production triangle builder; do not edit. */\n#pragma once\n");
    fprintf(header,"#define ECHOY_TRIANGLE_TABLE_RATE %uu\n#define ECHOY_TRIANGLE_TABLE_SIZE %uu\n#define ECHOY_TRIANGLE_TABLE_COUNT %uu\n",ECHOY_AUDIO_SAMPLE_RATE,TRIANGLE_SIZE,count);
    fprintf(header,"static const unsigned echoy_triangle_harmonics[%u] = {",count);
    for(unsigned n=0;n<count;n++)fprintf(header,"%s%uu",n?",":"",counts[n]);
    fprintf(header,"};\nstatic const float echoy_triangle_tables[%u][%u] = {\n",count,TRIANGLE_SIZE);
    for(unsigned n=0;n<count;n++) {
        triangle_table(work->triangle[0],counts[n],work->sine);
        fprintf(header,"{\n");
        for(unsigned j=0;j<TRIANGLE_SIZE;j++) {
            float sample=work->triangle[0][j]; uint32_t bits;unsigned char bytes[4];
            memcpy(&bits,&sample,4);echoy_fixed_put(bytes,bits);
            if(fwrite(bytes,1,4,binary)!=4) { free(work);fclose(header);fclose(binary);return 1; }
            fprintf(header,"%af%s%s",(double)sample,j+1<TRIANGLE_SIZE?",":"",j%8==7?"\n":"");
        }
        fprintf(header,"}%s\n",n+1<count?",":"");
    }
    fprintf(header,"};\n");
    bool ok=!ferror(header) && !ferror(binary);
    if(fclose(header))ok=false;
    if(fclose(binary))ok=false;
    free(work);return ok?0:1;
}
