#!/usr/bin/env python3
"""Expand the exact bounded SHORT_VOICINGS search in reference/harmony.js."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generate():
    data = json.loads((ROOT / 'tools/harmony-voicings.json').read_text())
    lines = ['// SPDX-License-Identifier: Apache-2.0', '// Generated by tools/generate_voicings.py; do not edit.',
             'static const chord_t chords[] = {']
    for chord in data['chords']:
        lines.append('    {{' + ','.join(map(str, chord['notes'])) + '}}, /* ' + chord['name'] + ' */')
    lines += ['};', 'static const voicing_t short_voicings[] = {']
    count = 0
    for index, chord in enumerate(data['chords']):
        pcs = {n % 12 for n in chord['notes']}
        for low in range(data['low'][0], data['low'][1]+1):
            if low % 12 not in pcs:
                continue
            for mid in range(low+data['midMinInterval'], min(low+data['midMaxInterval'], data['midMax'])+1):
                if mid % 12 not in pcs or mid % 12 == low % 12:
                    continue
                for high in range(max(data['highMin'],mid+data['highMinInterval']), min(low+data['highMaxSpan'], data['highMax'])+1):
                    if high % 12 in pcs and high % 12 not in {low % 12, mid % 12}:
                        lines.append(f'    {{{index}, {{{low},{mid},{high}}}}},')
                        count += 1
    lines += ['};', f'/* {count} candidates, in exact CHORDS/low/mid/high iteration order. */', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'components/echoy_core/harmony_voicings.inc'
    result = generate()
    if args.check:
        assert path.read_text() == result, 'voicing table is stale'
        print('PASS generated voicing table')
    else:
        path.write_text(result)
