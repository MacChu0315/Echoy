#!/usr/bin/env python3
"""Generate cached native-property defaults from the scene, not hand-coded IDs."""
from pathlib import Path
import json

def generate(scene, output):
    objects=json.loads(Path(scene).read_text())['objects']; rows=[]
    for obj in sorted(objects,key=lambda o:o.get('name','')):
        name=obj.get('name')
        if not name: continue
        color=obj.get('fg_color') if obj['type'] in ('label','progress') else obj.get('bg_color')
        color=int(color[1:7],16) if isinstance(color,str) and color.startswith('#') else -1
        def default(value):return value.get('default',0) if isinstance(value,dict) else value
        rows.append('    {%s, GSP_ECHOY_OBJ_KEY_%s, %d, %d, %d, %d, %d, %d, %d, %d, %s},' % (
            json.dumps(name),name.upper(),not obj.get('hidden',False),obj.get('enabled',True),
            color,default(obj.get('value',0)),default(obj.get('y',0)),default(obj.get('x',0)),default(obj.get('opacity',255)),round(default(obj.get('scale',1))*65536),
            json.dumps(obj['text'],ensure_ascii=False) if 'text' in obj else 'NULL'))
    Path(output).write_text('/* Generated by tools/generate_view_keys.py; do not edit. */\nstatic const view_default_t view_defaults[] = {\n'+'\n'.join(rows)+'\n};\n')
if __name__=='__main__':
    root=Path(__file__).resolve().parents[1]
    generate(root/'projects/echoy/ui/main.json',root/'projects/echoy/main/echoy_view_keys.h')
